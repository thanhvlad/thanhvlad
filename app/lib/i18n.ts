const dictionaries: Record<Locale, Partial<Record<I18nKey, string>>> = { en, vi };

/** Values substituted into `{name}` placeholders in a string. */
export type I18nVars = Record<string, string | number>;

/**
 * Look up a key, substituting any `{name}` placeholders.
 *
 * Placeholders rather than concatenation: word order differs between languages,
 * and "5 products removed" has to be able to become "Đã gỡ 5 sản phẩm" without
 * the call site knowing which half comes first.
 */
export function translate(locale: Locale, key: I18nKey, vars?: I18nVars): string {
  const raw = dictionaries[locale]?.[key] ?? en[key];
  if (!vars || !raw) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

export function makeT(locale: Locale) {
  return (key: I18nKey, vars?: I18nVars) => translate(locale, key, vars);
}

export type Translator = ReturnType<typeof makeT>;

export const SUPPORTED_LOCALES: Array<{ value: Locale; label: string }> = [
  { value: "en", label: "English" },
  { value: "vi", label: "Tiếng Việt" },
];

/** Coverage of a locale, used by the settings page to be honest about it. */
export function localeCoverage(locale: Locale): { translated: number; total: number; percent: number } {
  const total = Object.keys(en).length;
  const translated = Object.keys(dictionaries[locale] ?? {}).length;
  return { translated, total, percent: Math.round((translated / total) * 100) };
}
